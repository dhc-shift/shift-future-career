export const jobsFor = (companyType) => JOBS.filter((job) => job.types.includes(companyType));

/* 지원 유형·직무에 맞는 문항을 만든다. 문항 id는 유형·직무·순번으로 고정해 답변이 보존되게 한다. */
export function buildQuestions(companyType, jobId, organization = '') {
  const set = QUESTION_SETS[companyType]?.[jobId] || [];
  const org = organization.trim() || (companyType === 'public' ? '지원 기관' : '지원 기업');
  return set.map((item, index) => ({
    id: `${companyType}-${jobId}-q${index + 1}`,
    question: item.question.replaceAll('{org}', org),
    writingGuide: item.guide
  }));
}
